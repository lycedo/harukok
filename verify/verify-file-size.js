'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { parseFileSize, convertFileSize } = require('../tools/file-size-converter');
const find = (value, unit, result) => convertFileSize(value, unit).find(item => item.unit === result).value;
assert.equal(find('1', 'KB', 'B'), '1,000');
assert.equal(find('1', 'KiB', 'B'), '1,024');
assert.equal(find('1', 'GiB', 'B'), '1,073,741,824');
assert.equal(find('1', 'GiB', 'GB'), '1.073742');
assert.equal(find('1.5', 'MiB', 'KiB'), '1,536');
assert.equal(find('1,000', 'MB', 'GB'), '1');
assert.equal(find('0', 'B', 'TiB'), '0');
assert.equal(find('1', 'B', 'TiB'), '0.000001 미만');
assert.equal(find('1000000000000', 'TiB', 'B'), '1,099,511,627,776,000,000,000,000');
assert.equal(parseFileSize('0.000001'), 1n);
for (const value of ['', '-1', '1e3', '1,2', '.5', '1.0000001', '1000000000000.000001', 'Infinity']) assert.throws(() => parseFileSize(value));
assert.throws(() => convertFileSize('1', '__proto__'));
const names = ['size-form', 'size-value', 'size-unit', 'size-result', 'size-output', 'size-error', 'copy-status', 'size-example', 'copy-size'];
const elements = Object.fromEntries(names.map(name => [name, { value: '', textContent: '', hidden: true, handlers: {}, addEventListener(type, fn) { this.handlers[type] = fn; }, scrollIntoView() {}, focus() { this.focused = true; }, select() { this.selected = true; } }]));
const submit = () => elements['size-form'].handlers.submit({ preventDefault() {} });
elements['size-form'].requestSubmit = submit;
const clipboard = { writeText: async text => { clipboard.text = text; } };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../tools/file-size-converter.js'), 'utf8'), { document: { getElementById: id => elements[id] }, navigator: { clipboard } });
submit(); assert.ok(elements['size-error'].textContent); assert.equal(elements['size-result'].hidden, true);
elements['size-example'].handlers.click(); assert.equal(elements['size-result'].hidden, false); assert.match(elements['size-output'].value, /1,024 MiB/);
elements['size-value'].value = '2'; elements['size-form'].handlers.input(); assert.equal(elements['size-result'].hidden, true);
assert.equal(elements['size-output'].value, ''); assert.equal(elements['size-value'].value, '2');
submit(); assert.equal(elements['size-result'].hidden, false);
(async () => {
  await elements['copy-size'].handlers.click(); assert.equal(clipboard.text, elements['size-output'].value);
  clipboard.writeText = async () => { throw new Error('denied'); };
  await elements['copy-size'].handlers.click(); assert.match(elements['copy-status'].textContent, /직접/); assert.equal(elements['size-output'].selected, true);
  let resolve; clipboard.writeText = () => new Promise(done => { resolve = done; });
  const pending = elements['copy-size'].handlers.click(); elements['size-form'].handlers.change(); resolve(); await pending;
  assert.equal(elements['copy-status'].textContent, '');
  console.log('PASS - file size decimal/binary conversion, exact large integers, boundaries, UI recovery, clipboard fallback and stale state');
})().catch(error => { console.error(error); process.exitCode = 1; });
